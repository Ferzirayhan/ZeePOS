import { createHash } from 'node:crypto'
import type { Plugin } from 'vite'

export function collectPrecacheAssets(fileNames: Iterable<string>): string[] {
  const emittedAssets = [...fileNames]
    .filter((fileName) => /(?:^|\/)index\.html$|\.(?:js|css)$/i.test(fileName))
    .map((fileName) => `/${fileName.replace(/^\/+/, '')}`)

  return [...new Set(['/', '/index.html', ...emittedAssets])].sort((a, b) => {
    if (a === '/') return -1
    if (b === '/') return 1
    if (a === '/index.html') return -1
    if (b === '/index.html') return 1
    return a.localeCompare(b)
  })
}

export function buildServiceWorker(appShell: string[]): string {
  const version = createHash('sha256').update(JSON.stringify(appShell)).digest('hex').slice(0, 12)

  return `// Generated by the ZeePOS Vite build. Catalog shell only; never API/auth data.
const CACHE_NAME = 'zeepos-shell-${version}'
const APP_SHELL = ${JSON.stringify(appShell, null, 2)}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const { request } = event
  const url = new URL(request.url)
  const isRemoteBackend = url.hostname.endsWith('.supabase.co')
  const isSensitivePath = url.pathname.includes('/auth/') ||
    url.pathname.includes('/rest/v1/') ||
    url.pathname.includes('/api/')

  if (request.method !== 'GET' || isRemoteBackend || isSensitivePath) return

  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('/index.html')))
    return
  }

  if (url.origin === self.location.origin && APP_SHELL.includes(url.pathname)) {
    event.respondWith(caches.match(request).then((cached) => cached || fetch(request)))
  }
})
`
}

export function serviceWorkerBuildPlugin(): Plugin {
  return {
    name: 'zeepos-service-worker-build',
    apply: 'build',
    generateBundle(_options, bundle) {
      const appShell = collectPrecacheAssets(Object.values(bundle).map((entry) => entry.fileName))
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: buildServiceWorker(appShell),
      })
    },
  }
}
